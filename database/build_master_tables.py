import json
import sqlite3
from datetime import datetime, timezone


def create_build_master_tables(use_postgres=False, db_path=None):
    if use_postgres:
        from database.postgres_db import get_connection

        with get_connection() as db:
            db.execute("""
                CREATE TABLE IF NOT EXISTS player_builds (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    player_id BIGINT NOT NULL UNIQUE
                        REFERENCES players(id) ON DELETE CASCADE,
                    stats TEXT NOT NULL DEFAULT '{}',
                    highlights TEXT NOT NULL DEFAULT '[]',
                    tip TEXT NOT NULL DEFAULT '',
                    updated_at TEXT NOT NULL DEFAULT ''
                )
            """)
    else:
        if not db_path:
            raise ValueError("SQLite uchun db_path kerak")

        with sqlite3.connect(db_path) as db:
            db.execute("""
                CREATE TABLE IF NOT EXISTS player_builds (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    player_id INTEGER NOT NULL UNIQUE
                        REFERENCES players(id) ON DELETE CASCADE,
                    stats TEXT NOT NULL DEFAULT '{}',
                    highlights TEXT NOT NULL DEFAULT '[]',
                    tip TEXT NOT NULL DEFAULT '',
                    updated_at TEXT NOT NULL DEFAULT '',
                    FOREIGN KEY (player_id) REFERENCES players(id)
                        ON DELETE CASCADE
                )
            """)

    print("BUILD MASTER: player_builds jadvali tayyor.")
