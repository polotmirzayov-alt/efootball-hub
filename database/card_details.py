import json
import sqlite3
from datetime import datetime, timezone


def create_card_details_tables(use_postgres=False, db_path=None):
    if use_postgres:
        from database.postgres_db import get_connection

        with get_connection() as db:
            db.execute("""
                CREATE TABLE IF NOT EXISTS player_cards (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    player_id BIGINT NOT NULL REFERENCES players(id)
                        ON DELETE CASCADE,
                    card_name TEXT NOT NULL DEFAULT '',
                    card_type TEXT NOT NULL DEFAULT 'Standard',
                    rating INTEGER NOT NULL DEFAULT 0,
                    position TEXT NOT NULL DEFAULT '',
                    playing_style TEXT NOT NULL DEFAULT '',
                    image TEXT NOT NULL DEFAULT '',
                    release_date TEXT NOT NULL DEFAULT '',
                    source TEXT NOT NULL DEFAULT 'manual'
                )
            """)

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_card_details (
                    card_id BIGINT PRIMARY KEY
                        REFERENCES player_cards(id) ON DELETE CASCADE,
                    base_ovr INTEGER,
                    max_ovr INTEGER,
                    height_cm INTEGER,
                    weight_kg INTEGER,
                    age INTEGER,
                    stats TEXT NOT NULL DEFAULT '{}',
                    position_ratings TEXT NOT NULL DEFAULT '{}',
                    skills TEXT NOT NULL DEFAULT '[]',
                    boosters TEXT NOT NULL DEFAULT '[]',
                    max_build TEXT NOT NULL DEFAULT '{}',
                    physics TEXT NOT NULL DEFAULT '{}',
                    roles TEXT NOT NULL DEFAULT '{}',
                    source TEXT NOT NULL DEFAULT 'manual',
                    updated_at TEXT NOT NULL DEFAULT ''
                )
            """)
    else:
        if not db_path:
            raise ValueError("SQLite uchun db_path kerak")

        with sqlite3.connect(db_path) as db:
            db.execute("PRAGMA foreign_keys = ON")

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_cards (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    player_id INTEGER NOT NULL REFERENCES players(id)
                        ON DELETE CASCADE,
                    card_name TEXT NOT NULL DEFAULT '',
                    card_type TEXT NOT NULL DEFAULT 'Standard',
                    rating INTEGER NOT NULL DEFAULT 0,
                    position TEXT NOT NULL DEFAULT '',
                    playing_style TEXT NOT NULL DEFAULT '',
                    image TEXT NOT NULL DEFAULT '',
                    release_date TEXT NOT NULL DEFAULT '',
                    source TEXT NOT NULL DEFAULT 'manual'
                )
            """)

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_card_details (
                    card_id INTEGER PRIMARY KEY
                        REFERENCES player_cards(id) ON DELETE CASCADE,
                    base_ovr INTEGER,
                    max_ovr INTEGER,
                    height_cm INTEGER,
                    weight_kg INTEGER,
                    age INTEGER,
                    stats TEXT NOT NULL DEFAULT '{}',
                    position_ratings TEXT NOT NULL DEFAULT '{}',
                    skills TEXT NOT NULL DEFAULT '[]',
                    boosters TEXT NOT NULL DEFAULT '[]',
                    max_build TEXT NOT NULL DEFAULT '{}',
                    physics TEXT NOT NULL DEFAULT '{}',
                    roles TEXT NOT NULL DEFAULT '{}',
                    source TEXT NOT NULL DEFAULT 'manual',
                    updated_at TEXT NOT NULL DEFAULT ''
                )
            """)

    # PESDB manba ID si va takroriy kartalardan himoya.
    if use_postgres:
        from database.postgres_db import get_connection
        with get_connection() as db:
            db.execute("""
                ALTER TABLE player_cards
                ADD COLUMN IF NOT EXISTS source_card_id TEXT
            """)
            db.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS
                idx_player_cards_source_card_id
                ON player_cards (source, source_card_id)
                WHERE source_card_id IS NOT NULL
                  AND source_card_id <> ''
            """)
    else:
        with sqlite3.connect(db_path) as db:
            columns = {
                row[1] for row in
                db.execute("PRAGMA table_info(player_cards)").fetchall()
            }
            if "source_card_id" not in columns:
                db.execute(
                    "ALTER TABLE player_cards ADD COLUMN source_card_id TEXT"
                )
            db.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS
                idx_player_cards_source_card_id
                ON player_cards (source, source_card_id)
                WHERE source_card_id IS NOT NULL
                  AND source_card_id <> ''
            """)

    # Eski bazalarga ustunlarni ma'lumotlarni o'chirmasdan qo'shish.
    if use_postgres:
        from database.postgres_db import get_connection
        with get_connection() as db:
            db.execute("""
                ALTER TABLE player_card_details
                ADD COLUMN IF NOT EXISTS physics TEXT NOT NULL DEFAULT '{}'
            """)
            db.execute("""
                ALTER TABLE player_card_details
                ADD COLUMN IF NOT EXISTS roles TEXT NOT NULL DEFAULT '{}'
            """)
    else:
        with sqlite3.connect(db_path) as db:
            columns = {
                row[1] for row in
                db.execute("PRAGMA table_info(player_card_details)").fetchall()
            }
            if "physics" not in columns:
                db.execute(
                    "ALTER TABLE player_card_details "
                    "ADD COLUMN physics TEXT NOT NULL DEFAULT '{}'"
                )
            if "roles" not in columns:
                db.execute(
                    "ALTER TABLE player_card_details "
                    "ADD COLUMN roles TEXT NOT NULL DEFAULT '{}'"
                )

    print("PLAYER CARD DETAILS: jadvallar tayyor.")
