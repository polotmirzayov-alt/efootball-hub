import json
import sqlite3
from datetime import datetime, timezone


def create_card_details_tables(use_postgres=False, db_path=None):
    if use_postgres:
        from database.postgres_db import get_connection

        with get_connection() as db:
            db.execute("""
                CREATE TABLE IF NOT EXISTS player_cards (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    player_id BIGINT NOT NULL REFERENCES players(id)
                        ON DELETE CASCADE,
                    card_name TEXT NOT NULL DEFAULT '',
                    card_type TEXT NOT NULL DEFAULT 'Standard',
                    rating INTEGER NOT NULL DEFAULT 0,
                    position TEXT NOT NULL DEFAULT '',
                    playing_style TEXT NOT NULL DEFAULT '',
                    image TEXT NOT NULL DEFAULT '',
                    release_date TEXT NOT NULL DEFAULT '',
                    source TEXT NOT NULL DEFAULT 'manual'
                )
            """)

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_card_details (
                    card_id BIGINT PRIMARY KEY
                        REFERENCES player_cards(id) ON DELETE CASCADE,
                    base_ovr INTEGER,
                    max_ovr INTEGER,
                    height_cm INTEGER,
                    weight_kg INTEGER,
                    age INTEGER,
                    stats TEXT NOT NULL DEFAULT '{}',
                    position_ratings TEXT NOT NULL DEFAULT '{}',
                    skills TEXT NOT NULL DEFAULT '[]',
                    boosters TEXT NOT NULL DEFAULT '[]',
                    max_build TEXT NOT NULL DEFAULT '{}',
                    source TEXT NOT NULL DEFAULT 'manual',
                    updated_at TEXT NOT NULL DEFAULT ''
                )
            """)
    else:
        if not db_path:
            raise ValueError("SQLite uchun db_path kerak")

        with sqlite3.connect(db_path) as db:
            db.execute("PRAGMA foreign_keys = ON")

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_cards (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    player_id INTEGER NOT NULL REFERENCES players(id)
                        ON DELETE CASCADE,
                    card_name TEXT NOT NULL DEFAULT '',
                    card_type TEXT NOT NULL DEFAULT 'Standard',
                    rating INTEGER NOT NULL DEFAULT 0,
                    position TEXT NOT NULL DEFAULT '',
                    playing_style TEXT NOT NULL DEFAULT '',
                    image TEXT NOT NULL DEFAULT '',
                    release_date TEXT NOT NULL DEFAULT '',
                    source TEXT NOT NULL DEFAULT 'manual'
                )
            """)

            db.execute("""
                CREATE TABLE IF NOT EXISTS player_card_details (
                    card_id INTEGER PRIMARY KEY
                        REFERENCES player_cards(id) ON DELETE CASCADE,
                    base_ovr INTEGER,
                    max_ovr INTEGER,
                    height_cm INTEGER,
                    weight_kg INTEGER,
                    age INTEGER,
                    stats TEXT NOT NULL DEFAULT '{}',
                    position_ratings TEXT NOT NULL DEFAULT '{}',
                    skills TEXT NOT NULL DEFAULT '[]',
                    boosters TEXT NOT NULL DEFAULT '[]',
                    max_build TEXT NOT NULL DEFAULT '{}',
                    source TEXT NOT NULL DEFAULT 'manual',
                    updated_at TEXT NOT NULL DEFAULT ''
                )
            """)

    print("PLAYER CARD DETAILS: jadvallar tayyor.")
