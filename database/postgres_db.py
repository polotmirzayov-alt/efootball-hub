import os
import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.environ.get("DATABASE_URL")


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL environment variable is not set")

    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def create_tables():
    with get_connection() as db:
        db.execute("""
            CREATE TABLE IF NOT EXISTS players (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                nationality TEXT DEFAULT '',
                club TEXT DEFAULT '',
                position TEXT DEFAULT '',
                rating INTEGER DEFAULT 0,
                level INTEGER DEFAULT 1,
                playing_style TEXT DEFAULT '',
                card_type TEXT DEFAULT 'Standard',
                image TEXT DEFAULT ''
            )
        """)

        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS nationality TEXT DEFAULT ''
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS club TEXT DEFAULT ''
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS position TEXT DEFAULT ''
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS rating INTEGER DEFAULT 0
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS level INTEGER DEFAULT 1
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS playing_style TEXT DEFAULT ''
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS card_type TEXT DEFAULT 'Standard'
        """)
        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS image TEXT DEFAULT ''
        """)


        db.execute("""
            ALTER TABLE players
            ADD COLUMN IF NOT EXISTS efootball_id TEXT
        """)
        db.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS idx_players_efootball_id
            ON players (efootball_id)
            WHERE efootball_id IS NOT NULL AND efootball_id != ''
        """)


